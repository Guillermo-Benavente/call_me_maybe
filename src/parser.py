from argparse import Namespace, ArgumentParser
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter, ValidationError


class Prompt(BaseModel):
    """Represent an input prompt."""
    model_config = ConfigDict(extra="forbid")

    prompt: str = Field(strict=True, min_length=1)


class ParameterDefinition(BaseModel):
    """Represent a function parameter definition."""
    model_config = ConfigDict(extra="forbid")

    type: str = Field(strict=True, min_length=1)


class FunctionDefinition(BaseModel):
    """Represent an available function and its interface."""
    model_config = ConfigDict(extra="forbid")

    name: str = Field(strict=True, min_length=1)
    description: str = Field(strict=True, min_length=1)
    parameters: dict[str, ParameterDefinition]
    returns: ParameterDefinition


class FunctionGenerated(BaseModel):
    """Represent a function call generated by the language model."""
    model_config = ConfigDict(extra="forbid")

    name: str = Field(strict=True, min_length=1)
    parameters: dict[str, int | float | str | bool]


class Parser:
    """Parse command-line arguments and validate input JSON files."""

    def __init__(self) -> None:
        """Initialize the parser and load the input configurations.

        Parses command-line arguments, resolves input and output paths,
        and loads and validates the prompt and function definitions.

        Raises:
            ValueError: If an input file cannot be read, contains invalid
                JSON, or does not match its expected Pydantic schema.
        """
        self.args: Namespace = self._parse_arguments()

        self.input_path: Path = self.args.input
        self.functions_path: Path = self.args.functions_definition
        self.output_path: Path = self.args.output

        self.prompts: list[Prompt] = []
        self.functions: list[FunctionDefinition] = []

        try:
            self.prompts_json: str = self.compact_json(self.input_path)
            self.functions_json: str = self.compact_json(self.functions_path)

            self.prompts = self._load_json(
                self.input_path,
                list[Prompt],
            )

            self.functions = self._load_json(
                self.functions_path,
                list[FunctionDefinition],
            )

        except (OSError, json.JSONDecodeError, ValidationError) as error:
            raise ValueError(f"Input configuration error: {error}") from error

    @staticmethod
    def _parse_arguments() -> Namespace:
        """Parse command-line arguments.

        Defines the available input, function definition, and output
        file paths, using project-relative default locations.

        Returns:
            A Namespace containing the parsed command-line arguments.
        """
        project_root: Path = Path(__file__).resolve().parent.parent

        arg_parser: ArgumentParser = ArgumentParser(
            description="Call Me Maybe - Function Calling"
        )

        arg_parser.add_argument(
            "--input",
            type=Path,
            default=project_root / "data/input/function_calling_tests.json",
        )

        arg_parser.add_argument(
            "--functions_definition",
            type=Path,
            default=project_root / "data/input/functions_definition.json",
        )

        arg_parser.add_argument(
            "--output",
            type=Path,
            default=project_root / "data/output/function_calling_results.json",
        )

        return arg_parser.parse_args()

    @staticmethod
    def _load_json(file_path: Path, schema: Any) -> Any:
        """Load and validate a JSON file against a given schema.

        Checks whether the specified file exists, reads its contents,
        and validates the JSON data using a Pydantic TypeAdapter.

        Args:
            file_path: Path to the JSON file to load.
            schema: Expected schema used to validate the JSON data.

        Returns:
            The validated data returned by Pydantic.

        Raises:
            FileNotFoundError: If the specified file does not exist.
            OSError: If the file cannot be read.
            ValidationError: If the JSON data does not match the schema.
        """
        if not file_path.is_file():
            raise FileNotFoundError(f"File not found: {file_path}")

        adapter: TypeAdapter[Any] = TypeAdapter(schema)

        return adapter.validate_json(
            file_path.read_text(encoding="utf-8")
        )

    @staticmethod
    def validate_str_to_json(possible_json: str, schema: Any) -> Any:
        """Validate a JSON string against a given schema.

        Args:
            possible_json: JSON string to validate.
            schema: Expected schema used to validate the JSON data.

        Returns:
            The validated data returned by Pydantic.

        Raises:
            ValidationError: If the JSON data does not match the schema.
        """
        adapter: TypeAdapter[Any] = TypeAdapter(schema)

        return adapter.validate_json(possible_json)

    @staticmethod
    def compact_json(file: Path) -> str:
        """Read a JSON file and return its compact representation.

        Removes unnecessary whitespace while preserving non-ASCII
        characters.

        Args:
            file: Path to the JSON file to read.

        Returns:
            A compact JSON string representing the file contents.

        Raises:
            OSError: If the file cannot be read.
            json.JSONDecodeError: If the file contains invalid JSON.
        """
        data = json.loads(file.read_text(encoding="utf-8"))
        final_json = json.dumps(
            data, ensure_ascii=False,
            separators=(",", ":")
        )

        return final_json
